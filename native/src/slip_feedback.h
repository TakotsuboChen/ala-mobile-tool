/**
 * 滑移率反馈（振感 + 视觉）信号源——**两条独立归一化通道，取大**。
 *
 * 每物理帧在 `carController` 之后调用一次（见 pedal_hook.c 的
 * `proxy_car_controller` 尾部），读玩家车 4 个轮子的滑移量与载荷自适应峰值，
 * 逐轮算「纵向归一化滑移」与「横向归一化滑移」，各自取 4 轮最大值，**分别
 * 映射后取大**作为整车反馈电平。
 *
 * ## 八轮迭代的结论（改之前先读懂这张表）
 *
 * | 轮次 | 锚点 | 用户反馈 |
 * |---|---|---|
 * | v1 | 轮级 `maxSlip` | 「大 G 值过弯响胎时几乎不振」 |
 * | v2 | 整车 `slipVelo`（4 轮平均） | 「单侧空转振幅太小」；「过弯没完全打滑振幅居然能超过踩死油门」 |
 * | v3 | `hypot(σ/maxSlip, α/maxAngle)` | 「顶着墙对了/起步好转/**低速打方向还是太振**」 |
 * | v4 | 滑移**速度**比 | **彻底失败**：`LV.z ≈ 0` ⇒ 退化常数 ⇒ 「一直在振没停过」 |
 * | v5 | 两通道取大 + 横向封顶 | 「起步依旧满振」；且「又变回非常振且糊的共振感」 |
 * | v8 | **量纲闭合**（σ 不再二次归一化） | 「起步仍满振、锁死不够振」 |
 * | v9 | 锚点按实测分档重标定（静默 1 / 膝盖 4 / 满振 10） | 「低速好了」但**「漂移侧滑几乎一点不振」** |
 * | v10 | 横向拆成 **max_i（封顶 1/4）+ min_i（不封顶）** 两条通道 | 「漂移还是不够振」 |
 * | v11 | 甩尾改锚**后轮 min α**；新增**油门门控的后轮空转通道** | —（本版） |
 *
 * ⚠️ **v9→v10 的教训**：v9 用实测分档修好了"普通过弯太振"，但横向只有一个
 * `max_i` 且硬封顶 ⇒ **推头（可控）与漂移（失控）输出完全相同**。用户原话
 * 「明明已经滑起来了也不振」指的就是这个：漂移时 `max_i` 早就 4~7、顶在 1/4
 * 上不动了。**判别量是 `min_i`（四轮里滑得最轻的那只）**——推头时后轮
 * min_i 只有 0.2~0.9，漂移时四轮一起滑、min_i 4.0~6.4。
 *
 * ### v8 的根因：`slipRatio` 是**已经归一化过**的量
 *
 * 前七轮的共同病根是**量纲没对上**。把 `IRDSWheel` 全字段拉出来逐条对拍
 * （dump.cs L14651 起 172 个字段）＋反汇编 `SlipRatio`(0x1a7da24) 全函数，
 * 才看清它在做什么：
 *
 * ```
 *   SlipRatio(radius, wMagnitud):
 *       ω  = |angularVelocity|(0x100)，先按 radius 归一
 *       s  = min(1, ω_norm / 8)                              ← 速度权重
 *       σ  = clamp(−LV.z(0x254) / max(wMagnitud, 1), ≥0) · s   ← 返回值
 * ```
 *
 * **同一个函数里也有 `fabs(angularVelocity)` 与 `LV.z(0x254)`**——所以
 * `slipRatio` 不是"原始滑移量"，而是那个函数的**输出**。物理上的滑移比是
 * `(v − ωR)/max(ωR, v)`，而"滑移速度"就是 `v − ωR`，正是 `−LV.z`；游戏把
 * 分母写成 `max(wMagnitud, 1)`、再乘一个速度权重 `s`。
 *
 * ⇒ **`slipRatio / maxSlip` 是双重归一化**（ψ(σ)/ψ_peak，分子分母各自已经
 * 除以一次尺度）。这就是矛盾的统一根因：
 *
 * - 锁死时 `slipRatio` 钉在 `min(1,·)` 的上界 ≈ 1，而 `maxSlip` ≈ 0.1
 *   ⇒ 比值只有 **10**；
 * - 普通起步时 `slipRatio` ≈ 0.3~0.7 ⇒ 比值 **3~7**。
 *
 * 两者差不到一个数量级 ⇒ **纵向通道永远拉不开档次**，无论怎么调映射都会
 * 同时出现「起步满振」与「锁死不够振」。
 *
 * ### v8 的三条结构性修法
 *
 * 1. **分子改 `|σ|`，不再除 `slipRatioClamp`(0x35C)**。`s = |σ| / maxSlip`
 *    与 `maxSlip` 同一量纲，上限实测 ≈ 10 —— 锁死（≈10）与跟车（≈1）自然差
 *    3 倍以上。⚠️ **不要**再除以 clamp：那会把量程压到 ≤ 1/1.05，满振点
 *    永远够不到（马达"从不满幅"的老问题）。
 *
 * 2. **膝盖以内用幂次上弯**（`t^SLIP_POW`，SLIP_POW = 0.6）。
 *    线性映射下 σ 在静默点之内电平恒 0、之后陡起 —— 手感是台阶。
 *    幂次让"小滑移就有一点点、大滑移迅速上来"，全程连续可感，这正是用户
 *    要的「线性马达清晰的手感」。**膝盖以后保持线性且斜率只降不升**
 *    ⇒ 用户否定过的「滑了就突然爆发」在数学上不可能。
 *
 * 2b. **锚点按实测分档重标定（2026-10-02）**。逐帧直方图给出真实分档：
 *     巡航 `z≈0.02~0.17` / 普通过弯 `0.88~2.40` / 极限过弯 `3.9~7.7` /
 *     锁死·空转 `10.2~10.75`（σ 饱和）。旧锚点（静默 0.40、膝盖 1.0、
 *     满振 3.5）把普通过弯整段推上 0.2~0.7 电平 —— 这就是用户
 *     「低速拐弯还是太振了，不符合抓地力实际情况」的量化根因。
 *     新锚点：静默 **1.0**、膝盖 **4.0**（= 1/4 电平）、满振 **10.0**（= 饱和点）。
 *     横向同理：静默 1.5、封顶 4.0（旧锚点 a≥1 即封顶 ⇒ 每次转弯都顶满）。
 *
 * 3. **六条通道取大**（v12 定案，见上方迭代表与文件内各 map_* 的注释）：
 *
 *    | 通道 | 输入 | 门控 | 静默 → 满振 |
 *    |---|---|---|---|
 *    | 纵向（刹车锁死） | `max_i\|σ_i\|/maxSlip_i` | — | 1.0 → 10.0（σ 饱和） |
 *    | 横向 A（用尽抓地力） | `v·sin(max_i\|α_i\|)`（侧向滑移速度 m/s） | — | 8.0 → **封顶 0.25** |
 *    | 横向 B（甩尾） | **后轮** `min\|α\|/maxAngle` | — | 3.5 → 5.5 |
 *    | 后轮空转（**最高优先级**） | **后轮** `max\|σ\|/maxSlip` | **油门>0.08 且后轮 slipVelo>2m/s** | 1.8 → 3.0 |
 *    | 车身侧滑角（惯性打转） | `atan2(\|bvx\|,\|bvz\|)`（度） | `√(bvx²+bvz²)>5m/s` | 20° → 45° |
 *    | 四轮集体饱和（宽滑） | 四轮 `mean(max(纵向z,横向z))` | 同上 | 1.0 → 3.0 |
 *
 *    ⚠️ 横向 A 的信号源换过三代（α 原始值 → `\|Fy\|/(μ·Fn)` → `α/maxAngle` →
 *    `v·sin α`），前两代均实测证伪，理由见 `native/src/slip_feedback.c` 常量区。
 *
 *    ⚠️ v10 用「全四轮 min」判甩尾是错的：外侧前轮转弯时 α 天然低（转过去了
 *    但没滑），会把 min 拉到 1~2 淹没真漂移（实测同帧 min_all=1.0 而
 *    min_rear=5.2）。**甩尾在物理上就是后轴现象** ⇒ 必须只看后轮。
 *    ⚠️ 后轮空转必须油门门控：不踩油门时后轮 σ 高只可能是刹车锁死或噪声。
 *
 * 3b. **横向封顶 1/4 的理由**。`SlipAngle`(0x1a7daa8) 与 `SlipRatio` 同构，分母被
 *    `max(..., 1)` 钳到 ≥ 1 m/s。低速纯滚动时真实值远小于 1 ⇒ 被钳 ⇒ α
 *    退化成 `atan(LV.x)`，而 `LV.x` 里含**打舵角本身贡献的合法横向速度**
 *    （轮胎坐标系随转向旋转后，原车速在轮胎系下产生 `v·sin(δ)` 的横向
 *    分量）。于是"打舵"被误读成"滑移"——实测归一化后可达峰值的 7 倍。
 *
 *    假象**无法从数据侧剔除**（要剔就得知道 LVelocity 的坐标系；v4 试过，
 *    反推得 `LV.z ≈ 0`、设计彻底退化）。所以用结构性防御：横向封顶 1/4。
 *    假象再大也只是 1/4 —— 而 1/4 恰好就是用户对"高 G 过弯用尽抓地力"的
 *    规格值，两者不冲突。
 *
 *    **为什么高速没这个假象**：游戏自己的
 *    `IRDSCarControllInput::LockSteerAtSlipAngle`(0x1a678c8) 在
 *    `max_i(|α|/maxAngle) > 0.60` 时把 maxSteerLock 缩到 `|inputSteer|` ——
 *    **高速时游戏根本不让打大舵角**，低速不锁 ⇒ 用户能打满 ⇒ 假象暴露。
 *    这解释了用户原话「越低速越振」「高速弯 300km/h+ 打满方向一点都不振」。
 *
 * ### 为什么不做 hypot 合成（v3 的病根）
 *
 * 摩擦圆上总利用率确实是 `hypot(σ/σ*, α/α*)`，但**反馈强度**的两个通道规格
 * 不同：纵向要求"锁死 = 满振"，横向要求"用尽抓地力 = 1/4 且不得更高"。
 * hypot 让横向把整车电平推高（假象 na = 7 ⇒ hypot ≈ 7 ⇒ 满振），正是 v3
 * 「低速打方向满振」的病根。取大则天然实现"横向封顶、纵向放开"。
 *
 * ### 为什么纵向不做对数压缩（v3 的另一个病根）
 *
 * v3 有一段 `decay_past_peak(x) = 1 + ln(x)·0.30`（x > 1 时）。它压缩的量
 * 是**有界**的，压缩后锁死只到 `1 + ln(10)·0.3 = 1.69`，**够不到满振点**
 * ⇒ 马达从未被推到满幅，这就是用户说的「最大振动强度变得非常弱」。
 * 有界量不需要压缩，已删除。
 *
 * ## 门控（缺失任意一条即输出 0）
 *
 * - **逐轮地面接触**：`normalForce`(0x138) > 0。反汇编实证 `ComputeWheelPhysics`
 *   的离地支把 `0x1a7e8e0` `str wzr,[x19,#0x138]`——轮子离地时这个字段被**显式
 *   清零**，是最干净的逐轮接触判据。不用 `contact`(0x390) /
 *   `colliderTouchingWheel`(0x3C0)：全 `.so` 扫描显示这两个字段在 `IRDSWheel`
 *   内部**只写不读**，语义不是"本帧是否着地"。
 * - **整车未全轮离地**：`allTiresOffGround`(0x168)。跳台/坠崖时四轮全在空中，
 *   此时所有滑移量都是**上一帧的残留值**，不清零会让腾空瞬间保持高电平。
 * - **车速门槛：无**。曾用 2.0 / 0.5 m/s，都挡掉了「顶着墙踩死油门疯狂空转
 *   烧胎」（车不动 ⇒ carSpeed≈0 ⇒ 判负）。静止本身会让 σ/α 双双归零，不需要
 *   车速门控兜。
 *
 * ## 采样时机
 *
 * `proxy_fixed_update` 的 tick **已废弃**：`IRDSCarControllInput.FixedUpdate`
 * (0x1a66c3c) 与 `multithreadWheelManager.FixedUpdate` (0x1a81e90) 是**两个独立
 * 的 Unity 回调**，Unity 不保证谁先跑。若 FixedUpdate 先于 `ComputeWheelPhysics`，
 * 读到的就是上一帧的滑移量。
 *
 * 采样点因此移到 `proxy_car_controller` 的 **orig 之后**：`carController()` 内部
 * 末尾 `0x1a67248-0x1a672c0` 正是"累加 4 轮 slipVelo → 除轮数"那段，跑在
 * `ComputeWheelPhysics` 之后，此处的轮级字段必是本帧新值。
 *
 * ## 玩家车过滤
 *
 * 只在 `is_target_player_car(this)` 为真的分支被调用，天然无 AI 误判。
 *
 * ## 标定探针
 *
 * 开启后每约 3 秒落一组实测数据到 `ala_tool_native.log`，自限时 10 分钟。
 * 输出各通道的峰值（`maxLon`/`maxLat`/`maxLatMin`，单位都是"该轮峰值 = 1"）、
 * `|σ|` 峰值、车速峰值、逐轮 Fn、原始 σ/α/maxSlip/maxAngle、LVelocity 三分量、
 * `slipRatioClamp`，以及**游戏自己算的 `unitSlip`(0x3F8) / `unitAngle`(0x3FC)**
 * ——最后这一对是 v8 新增的**外部校验锚点**：把 `unitSlip` 与 `|σ|/maxSlip`
 * 并排一看，本文档的量纲推断立刻可证伪。
 *
 * 回归三条锚点（数值来自 2026-10-02 实测分档）：
 *
 *   锁死 / 出弯空转 → `maxLon ≈ 10.2~10.75`（电平 1.0，σ 饱和）
 *   极限过弯        → `maxLon ≈ 3.9~7.7`（电平 0.25~0.7）
 *   漂移侧滑        → `maxLatMin ≈ 4.0~6.4`（电平 0.25~1.0，**四轮皆滑**）
 *   推头 / 响胎过弯 → `maxLat ≥ 4` 但 `maxLatMin ≤ 0.9`（电平 = 1/4）
 *   普通过弯 / 跟车 → `maxLon ≤ 2.4` 且 `maxLat ≤ 2.7`（电平 ≤ 0.2）
 */

/** 配置变更时下发（低频，同 pedal_set_tc_abs 模式，不重装 hook）。 */
void slip_feedback_set_params(int enabled, float full_z);

/** 查询当前反馈电平 0..1（Java 主线程轮询，无锁读 volatile）。 */
void slip_feedback_query(float *out_level);

/**
 * **按时间窗口采样**（推荐路径，2026-09-22 第九轮新增）。
 *
 * 与 [slip_feedback_query] 的区别：本函数返回**自 `from_seq` 以来**产生的
 * 全部电平样本（最多 `max` 个），并给出下一个待读序号。
 *
 * 为什么需要它：物理帧 50Hz、Java 轮询 60Hz，两者不同步。旧路径每次轮询只
 * 取"最新值"，于是**一帧被读两次、或整帧被漏掉**，抖动的快慢完全由两个时钟
 * 的相位差决定。当振感波形要**直接跟随信号的抖动**（而不是靠人为调制造质感）
 * 时，采样率的不确定会直接变成手感的"飘"。
 *
 * 拿它做**流式重发**：Java 每 20ms 取一次增量，把 N 个电平样本各对应成一段
 * 波形下发。波形的段序 = 物理帧序 ⇒ 幅度起伏 = 真实信号起伏，**没有任何
 * 人为调制频率**——这是"不糊"的质感来源。
 *
 * @param out      输出缓冲（调用方分配）
 * @param max      缓冲容量（建议 ≥ 8）
 * @param from_seq 上次返回的 `*out_next_seq`（首次传 0 = 从当前开始）
 * @param out_next_seq 输出：下一个待读序号，原样回传即可
 * @return 实际写入的样本数（0 = 期间没有新样本）
 */
int slip_feedback_drain(float *out, int max, unsigned int from_seq,
                        unsigned int *out_next_seq);

/**
 * 每物理帧调用（玩家车白名单内，**必须在 carController 之后**）。
 * car_inputs = IRDSCarControllInput*。
 */
void slip_feedback_tick(void *car_inputs);

/** 标定探针开关（诊断用；自限时 10 分钟后自动关）。 */
void slip_feedback_set_probe(int enabled);

